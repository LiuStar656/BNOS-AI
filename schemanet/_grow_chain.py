# -*- coding: utf-8 -*-
"""教学侧多样扩链（2026-08-10，质量评估残留问题的下一步计划：
"但是→我看书"式链漂移 = 教学链单调 → 新增口语化教学句扩链）。

漂移点（质量报告）：
  但是→[我]→看→书 ×30（"但是我"散文桥 + "我看书"教学强链）
  所以→猫→睡觉 ×14（"所以猫想吃饭"教学链）
  玩→仍然→坚持 ×12（toutiao 词混入教学链表——已修 source 过滤）

扩链 20 句（全词表内、口语化、等权 ×R）：
  ① 正确替代链：但是我累了 / 我饿了就吃饭 / 天黑了就睡觉……
     ——"就"衔接链（对应幼儿口语"……就……"）
  ② 多样主语/事件：猫/他/我们/她 × 吃饭/睡觉/回家/买菜……
加载 v26.1 → 快照 v27.1 → 质量评估回归。

用法：python _grow_chain.py
"""

import time
from pathlib import Path

from schema_net import _learn_sentence
from snapshot import load_version, save_snapshot

RUNS_DIR = Path(__file__).parent / "runs"
R = 4                       # 等权轮数（与 v3 同档，防顶格）

# 扩链句（token 与 jieba 分词一致，全词表内已查证）
CHAIN_SENTS = [
    "但是我累了",              ["但是", "我", "累", "了"],
    "我饿了就吃饭",            ["我", "饿", "了", "就", "吃", "饭"],
    "猫饿了就吃饭",            ["猫", "饿", "了", "就", "吃", "饭"],
    "天黑了就睡觉",            ["天", "黑", "了", "就", "睡觉"],
    "下雨了就带伞",            ["下雨", "了", "就", "带", "伞"],
    "他累了就睡觉",            ["他", "累", "了", "就", "睡觉"],
    "我写完作业就看书",        ["我", "写", "完", "作业", "就", "看", "书"],
    "我们吃完饭就去公园",      ["我们", "吃", "完", "饭", "就", "去", "公园"],
    "猫吃完饭就睡觉",          ["猫", "吃", "完", "饭", "就", "睡觉"],
    "她放学了就回家",          ["她", "放学", "了", "就", "回家"],
    "天气冷了我就多穿衣服",    ["天气", "冷", "了", "我", "就", "多", "穿", "衣服"],
    "我早上起床就吃饭",        ["我", "早上", "起床", "就", "吃", "饭"],
    "我生病了就看医生",        ["我", "生病", "了", "就", "看医生"],
    "她认真写作业",            ["她", "认真", "写", "作业"],
    "我们一起去吃饭",          ["我们", "一起", "去", "吃", "饭"],
    "我晚上看书",              ["我", "晚上", "看", "书"],
    "她早上跑步",              ["她", "早上", "跑步"],
    "我们晚上看电视",          ["我们", "晚上", "看", "电视"],
    "爸爸在家做饭",            ["爸爸", "在", "家", "做", "饭"],
    "妈妈去超市买菜",          ["妈妈", "去", "超市", "买", "菜"],
]


def main():
    t0 = time.time()
    print("═══ 教学侧多样扩链：20 句口语化链 ×%d（等权）═══\n" % R)
    ng, vocab, pats, cursor = load_version("26.1")
    keys = set(pats.keys())
    missing = {w for toks in CHAIN_SENTS[1::2] for w in toks if w not in keys}
    print(f"[词表] {len(keys)} 词；扩链句词表外：{missing or '无'}")
    assert not missing, "扩链句含词表外词！"

    for toks in CHAIN_SENTS[1::2]:
        for _ in range(R):
            _learn_sentence(ng, toks, pats, slot=0)
    print(f"[教学] {len(CHAIN_SENTS)//2} 句 ×{R} 轮完成")

    save_snapshot(ng, parent="26.1",
                  tag="教学侧多样扩链：20 句口语化链（但是我累了/饿了就"
                      "吃饭/天黑了就睡觉…——就 衔接链，等权×4）",
                  metrics={"n_sents": len(CHAIN_SENTS)//2, "r": R},
                  vocab=vocab, pats=pats, cursor=cursor)
    print(f"[完成] v27.1 已存（{time.time()-t0:.0f}s）")


if __name__ == "__main__":
    main()
