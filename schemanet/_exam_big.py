# ── 判定：期望链约束读取（与 _grow_s23_v2 同款）──────────────
def chain_read(ng, pats, n2w, front, back):
    """引发边检查（front[-1]→back[0]）+ 顺序链读（每步只读期望链
    下一个词，top-k=8，叠词相邻重复直接推进）。返回 (读出序列, 断点)。"""
    if edge_between(ng, pats, front[-1], back[0]) <= 0:
        return [], (front[-1], back[0])
    seq = [back[0]]
    cur, rest = back[0], list(back[1:])
    for _ in range(len(rest) + 1):
        if not rest:
            break
        if rest[0] == cur:
            seq.append(cur)
            rest.pop(0)
            continue
        top = direct_next_multi(ng, pats, n2w, [cur], k=8, domain=set(back))
        nxt = next((w for w, _ in top if w == rest[0]), None)
        if not nxt:
            return seq, (cur, rest[0])
        seq.append(nxt)
        rest.pop(0)
        cur = nxt
    return seq, None


def oov_chain_read(ng, pats, n2w, front, back, keys):
    """期望链读取 + OOV 字造词（用户："检验是否能通过字造词"）。

    back 内词表外词 → 临时字模式并集身份（不落盘不改网络，v19 机制）：
      pats[oov] = 组成字的模式并集 → 读边 = 字边继承（如 吃→早饭
      = 吃→{早,饭} = 吃→早 + 吃→饭）；并集神经元映射改为 OOV 词名
      （读出"椅子"而非"椅"）。
    字不全在词表 → 无法造 → 断（缺字）。返回 (读出序列, 断点)。"""
    pats2 = dict(pats)
    for w in back:
        if w not in pats2:
            modes = []
            for ch in w:
                if ch not in pats2:
                    return [], (w, "缺字")
                modes.extend(pats2[ch])
            pats2[w] = sorted(set(modes))
    n2w2 = dict(n2w)
    for w, ns in pats2.items():
        if w not in pats:
            for j in ns:
                n2w2[j] = w
    return chain_read(ng, pats2, n2w2, front, back)


