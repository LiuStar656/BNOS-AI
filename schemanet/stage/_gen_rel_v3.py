"""Stage 3 v17 数据扩量：v2 现有 108 条 + 新增 58 条模板 = 166 条。

背景（2026-08-10 PLAN Stage3v17）：
  - 探测结论：散文全量先见后，108 条×2 轮后教拉不回配对直读断点
    （"虽然→但是"被散文全量竞争边碾压）→ v17 教学量翻倍（150+ 条）
  - 58 条新增模板全部词表内（miss=[]）；候选词已对 v16.0 词表查证
    （仅 喝水/起床/手帕 不可用，已避开）

来源：
  ① 现有 108 条 = 复用 stage3_rel_v2.json（逐条原样合并，不动）
  ② 新增 58 条 = 因果 +26 / 转折 +17 / 顺序 +15（对话·构造 + 短文·构造，
     句式结构镜像 v2 同款模板，主语/状态/动作/地点用新增词元）

新增词元（全部词表内，已查证）：主语 她/你们/他们；状态 热/渴/忙/疼/难过；
  动作 看书/上班/回家/做饭/吃药/洗澡/坚持（+写作业/上课 复用）；地点 医院/图书馆。

落档：data/curriculum/stage3_rel_v3.json
结构同 v2：[{"tokens": [...], "source": "...", "sent": "...", "miss": [...]}]

用法：python _gen_rel_v3.py
"""

import json
import sys
from pathlib import Path

from snapshot import load_version

DATA = Path(__file__).resolve().parent.parent / "data" / "curriculum"
V2 = DATA / "stage3_rel_v2.json"
OUT = DATA / "stage3_rel_v3.json"

# ── 新增模板用词（启动时自检全部在 v16.0 词表）───────────────────
CHECK_WORDS = ["她", "你们", "他们", "我们", "我", "你", "他", "猫", "狗",
               "热", "渴", "忙", "疼", "难过", "累", "困", "冷", "饿", "下雨",
               "看书", "写作业", "上班", "回家", "做饭", "吃饭", "吃药",
               "洗澡", "睡觉", "刷牙", "穿衣服", "上课", "坚持",
               "医院", "图书馆", "商店", "公园",
               "因为", "所以", "虽然", "但是", "先", "然后",
               "了", "想", "不", "仍然", "今天", "去", "看", "书", "写", "作业"]


def build_new_templates():
    """v17 新增 58 条模板（清单见 PLAN §四，用户已过目）。

    每条为 (tokens, source)：句式结构镜像 v2 同款模板，内容组合用新增词元。
    """
    rows = []

    # ── ① 因果组 +26（因为…所以…）─────────────────────────────
    # 对话·因果：因为[S 状态 了]所以[S 想 动作]
    C1 = [("她", "累", "睡觉"), ("他们", "饿", "吃饭"), ("你", "困", "睡觉"),
          ("她", "渴", "回家"), ("他", "忙", "上班"), ("你们", "冷", "穿衣服")]
    for s, st, act in C1:
        rows.append((["因为", s, st, "了", "所以", s, "想", act], "对话·构造"))
    # 对话·因果：因为[今天 状态]所以[S 动作]
    C2 = [("忙", "他", "上班"), ("渴", "她", "回家"),
          ("热", "猫", "睡觉"), ("疼", "他", "吃药")]
    for st, s, act in C2:
        rows.append((["因为", "今天", st, "所以", s, act], "对话·构造"))
    # 对话·因果：因为[状态]所以[S 不 动作]
    for st, s, act in C2:
        rows.append((["因为", st, "所以", s, "不", act], "对话·构造"))
    # 短文·因果：因为[S1 状态]所以[S2 动作]
    C3 = [("她", "渴", "她", "回家"), ("他", "忙", "他", "上班"),
          ("你", "冷", "你", "穿衣服"), ("狗", "饿", "狗", "吃饭")]
    for s1, st, s2, act in C3:
        rows.append((["因为", s1, st, "所以", s2, act], "短文·构造"))
    # 短文·因果：因为[S V O]所以[S V O]（V-O 拆词：看书=看+书、写作业=写+作业）
    C4 = [["因为", "她", "看", "书", "所以", "她", "写", "作业"],
          ["因为", "他", "上班", "所以", "他", "回家"],
          ["因为", "我", "做饭", "所以", "我", "吃饭"],
          ["因为", "他", "吃药", "所以", "他", "睡觉"]]
    for t in C4:
        rows.append((t, "短文·构造"))
    # 对话·因果：因为[状态]所以[S 动作]（无主）
    C5 = [("渴", "她", "回家"), ("忙", "他", "上班"),
          ("疼", "他", "吃药"), ("热", "我们", "回家")]
    for st, s, act in C5:
        rows.append((["因为", st, "所以", s, act], "对话·构造"))

    # ── ② 转折组 +17（虽然…但是…）─────────────────────────────
    # 对话·转折：虽然[S 状态 了]但是[S 仍然 动作]（狗饿→不吃饭 无"仍然"）
    T1 = [("她", "难过", "上课"), ("他", "疼", "坚持"), ("你", "困", "写作业"),
          ("他们", "忙", "上班"), ("她", "渴", "做饭")]
    for s, st, act in T1:
        rows.append((["虽然", s, st, "了", "但是", s, "仍然", act], "对话·构造"))
    rows.append((["虽然", "狗", "饿", "了", "但是", "狗", "不", "吃饭"], "对话·构造"))
    # 对话·转折：虽然[状态]但是[S 去 O]
    T2 = [("热", "我们", "公园"), ("疼", "他", "医院"),
          ("下雨", "我们", "图书馆"), ("渴", "我", "商店")]
    for st, s, place in T2:
        rows.append((["虽然", st, "但是", s, "去", place], "对话·构造"))
    # 短文·转折：虽然[S1 V]但是[S2 V O]
    T3 = [("她", "难过", "她", "上课"), ("他", "疼", "他", "坚持"),
          ("我们", "忙", "我们", "上班")]
    for s1, st, s2, v in T3:
        rows.append((["虽然", s1, st, "但是", s2, v], "短文·构造"))
    # 短文·转折：虽然[今天 状态]但是[S V]
    T4 = [["虽然", "今天", "热", "但是", "她", "回家"],
          ["虽然", "今天", "疼", "但是", "他", "去", "医院"],
          ["虽然", "今天", "下雨", "但是", "我们", "看", "书"],
          ["虽然", "今天", "忙", "但是", "他", "上班"]]
    for t in T4:
        rows.append((t, "短文·构造"))

    # ── ③ 顺序组 +15（先…然后…）───────────────────────────────
    # 对话·顺序：先[S 动作]然后[S 动作]
    X1 = [("她", "洗澡", "她", "睡觉"), ("他", "上班", "他", "回家"),
          ("我", "刷牙", "我", "上班"), ("我们", "做饭", "我们", "吃饭")]
    for s1, v1, s2, v2 in X1:
        rows.append((["先", s1, v1, "然后", s2, v2], "对话·构造"))
    # 短文·顺序：先[S V O]然后[S V O]（V-O 拆词：看书=看+书、写作业=写+作业）
    X2 = [["先", "她", "看", "书", "然后", "她", "写", "作业"],
          ["先", "他", "吃药", "然后", "他", "睡觉"],
          ["先", "我", "做饭", "然后", "我", "吃饭"]]
    for t in X2:
        rows.append((t, "短文·构造"))
    # 对话·顺序：先[动作]然后[S 动作]（主语后置，最自然口语）
    X3 = [["先", "上班", "然后", "他", "回家"],
          ["先", "看", "书", "然后", "我", "睡觉"],
          ["先", "做饭", "然后", "她", "吃饭"],
          ["先", "吃药", "然后", "他", "睡觉"],
          ["先", "洗澡", "然后", "他", "上班"]]
    for t in X3:
        rows.append((t, "对话·构造"))
    # 短文·顺序：先[S 动作 了]然后[S 动作]
    X4 = [["先", "她", "洗澡", "了", "然后", "她", "睡觉"],
          ["先", "他", "吃药", "了", "然后", "他", "睡觉"],
          ["先", "我们", "看", "书", "了", "然后", "我们", "睡觉"]]
    for t in X4:
        rows.append((t, "短文·构造"))

    return rows


def main():
    # ── 1. 加载 v16.0 词表 + 新增词自检 ────────────────────────
    ng, vocab, pats, cursor = load_version("16.0")
    keys = set(pats.keys())
    miss_check = [w for w in CHECK_WORDS if w not in keys]
    if miss_check:
        print(f"[自检] 新增模板用词缺 {len(miss_check)}：{miss_check}")
        print("  需要从模板中剔除或词表补词，脚本中止")
        raise SystemExit(1)
    print(f"[词表] v16.0 共 {len(keys)} 词，新增模板用词全部在表")

    # ── 2. 现有 108 条（复用 v2，逐条原样合并）─────────────────
    v2_rows = json.loads(V2.read_text(encoding="utf-8"))
    print(f"[现有] stage3_rel_v2.json：{len(v2_rows)} 条（原样复用）")

    # ── 3. 新增 58 条模板 ──────────────────────────────────────
    new_rows = build_new_templates()
    print(f"[新增] {len(new_rows)} 条（因果 "
          f"{sum(1 for t, _ in new_rows if '因为' in t)} / 转折 "
          f"{sum(1 for t, _ in new_rows if '虽然' in t)} / 顺序 "
          f"{sum(1 for t, _ in new_rows if '先' in t)}）")
    for t, src in new_rows[:6]:
        print(f"  {src}：{' '.join(t)}")

    # ── 4. 合并落档（166 条；新增模板词表内 miss=[]）────────────
    rows = [dict(r) for r in v2_rows]
    for t, src in new_rows:
        rows.append({"tokens": t, "source": src, "sent": "".join(t), "miss": []})

    n_causal = sum(1 for r in rows if "因为" in r["tokens"])
    n_turn = sum(1 for r in rows if "虽然" in r["tokens"])
    n_seq = sum(1 for r in rows if "先" in r["tokens"])
    print(f"\n[汇总] 共 {len(rows)} 条（因果 {n_causal} / 转折 {n_turn}"
          f" / 顺序 {n_seq}）")
    print(f"  来源分布：{ {src: sum(1 for r in rows if r['source'] == src)
                          for src in ['短文·真实', '对话·构造', '短文·构造']} }")
    print(f"  词表覆盖：{sum(1 for r in rows if not r['miss'])}/{len(rows)}"
          f" 条词表内（缺词条数 {sum(1 for r in rows if r['miss'])}，"
          f"全部为 v2 原有 toutiao 真实句，v16 已分配）")

    OUT.write_text(json.dumps(rows, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    print(f"\n[落档] {OUT}")


if __name__ == "__main__":
    main()
